export function getJourney(book, chapter) {
  const ids = BOOK_JOURNEY_MAP[book]
  if (!ids) return null
  const journeys = ids.map(id => JOURNEYS[id])
  const current = journeys.find(j => chapter >= j.chapterRange[0] && chapter <= j.chapterRange[1])
  if (current) return current
  const started = journeys.filter(j => j.chapterRange[0] <= chapter)
  return started.length ? started[started.length - 1] : journeys[0]
}
